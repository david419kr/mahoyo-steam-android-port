"""Emit verified Steam 1.1 / Korean 1.2 canvas pairs from prepared dimension tables."""
from pathlib import Path
import argparse
import re


def dimensions(path):
    if Path(path).stat().st_size>4*1024*1024:raise ValueError('Dimension table budget')
    lines=Path(path).read_text(encoding='utf-8').splitlines()
    if not lines or lines[0]!='WOH_IMAGE_DIMENSIONS1':raise ValueError('Invalid dimension table')
    result={}
    for line in lines[1:]:
        fields=line.split()
        if len(fields)!=3:raise ValueError('Invalid dimension row')
        key,w,h=fields
        if not re.fullmatch(r'[a-z0-9_][a-z0-9_.-]*\.(?:mzp|cbg)',key) or '..' in key or key in result:raise ValueError('Unsafe or duplicate image key')
        w,h=int(w),int(h)
        if not 1<=w<=65535 or not 1<=h<=65535 or w*h>64*1024*1024:raise ValueError('Image size budget')
        result[key]=(w,h)
    return result


def generate(original,korean,output):
    if Path(output).resolve() in (Path(original).resolve(),Path(korean).resolve()):raise ValueError('Output must not overwrite input tables')
    original,korean=dimensions(original),dimensions(korean)
    rows=[(key,original[key],size) for key,size in sorted(korean.items()) if key in original and size!=original[key]]
    text=['#pragma once','#include "bitmap_geometry.h"','namespace mahoyo::language {',
          '// Generated by tools/prepare_korean_geometry.py from verified Steam 1.1 / Korean patch 1.2 headers.',
          'struct KoreanCanvas {bitmap_geometry::Size original,korean;};',
          'inline const std::map<std::string,KoreanCanvas>& steam11KoreanCanvases(){',
          '    static const std::map<std::string,KoreanCanvas> value={']
    for key,a,b in rows:text.append(f'        {{"{key}",{{{{{a[0]},{a[1]}}},{{{b[0]},{b[1]}}}}}}},')
    text+=['    };return value;','}',
           'inline std::optional<bitmap_geometry::Resize> koreanCanvasResize(const std::string& key,bitmap_geometry::Size saved,bitmap_geometry::Size current){',
           '    const auto at=steam11KoreanCanvases().find(key);if(at==steam11KoreanCanvases().end())return std::nullopt;',
           '    const auto& pair=at->second;',
           '    if(!(saved==pair.original||saved==pair.korean)||!(current==pair.original||current==pair.korean))throw std::runtime_error("Unrecognized Korean canvas intrinsic dimensions");',
           '    if((saved==pair.original||saved==pair.korean)&&(current==pair.original||current==pair.korean)&&!(saved==current))return bitmap_geometry::Resize{saved,current};',
           '    return std::nullopt;','}','}']
    Path(output).write_text('\n'.join(text)+'\n',encoding='utf-8',newline='\n')
    return len(rows)


if __name__=='__main__':
    parser=argparse.ArgumentParser(__doc__);parser.add_argument('original',type=Path);parser.add_argument('korean',type=Path);parser.add_argument('output',type=Path)
    args=parser.parse_args();print('Verified canvas pairs:',generate(args.original,args.korean,args.output))
